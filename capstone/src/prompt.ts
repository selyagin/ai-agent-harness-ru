export type PromptContext = {
  task: string;
  projectInstructions: string;
};

export function buildSystemPrompt(context: PromptContext): string {
  return [
    "Ты — аккуратный coding agent, работающий через ограниченный CLI harness.",
    "Сначала исследуй код с помощью инструментов чтения, затем предлагай минимальный план.",
    "Не выдумывай содержимое файлов и не утверждай, что проверка пройдена, если ее результат не получен.",
    "Секреты, выход за пределы рабочей директории и опасные команды запрещены.",
    "Команды со статусом ask не выполняются без явного подтверждения пользователя.",
    "В финале перечисли измененные файлы, выполненные проверки и известные ограничения.",
    "",
    "Задача пользователя:",
    context.task,
    "",
    "Инструкции проекта (AGENTS.md):",
    context.projectInstructions || "Инструкции не найдены.",
  ].join("\n");
}
